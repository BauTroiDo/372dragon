#!/usr/bin/env python3
# CYS: Tests/abi/gen_abi_asserts.py - writes Src/Shared/Common/abi_asserts.h from the x86/x64 ABI dumps (Docs/04 6.2).
#
# One static_assert(sizeof(T) == N) per namespace-scope struct/union of Src/Shared/Common that is a candidate for
# being sent or stored as raw bytes: not polymorphic, no pointer/handle members (directly or nested), and the same size
# on x86 and x64. N is the x86 size of Registry/abi/struct_sizes_x86.json. The header is compiled by
# Src/Shared/Common/abi_asserts.cpp (part of cys_wxnetpackets), so a later change of any of these sizes fails the
# build on both architectures instead of silently changing the wire/DB format.
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
REG = os.path.join(ROOT, 'Registry', 'abi')
OUT = os.path.join(ROOT, 'Src', 'Shared', 'Common', 'abi_asserts.h')
PTR_RE = re.compile(r'\*|\b(LP[A-Z]*STR|LPVOID|PVOID|HANDLE|HWND|HINSTANCE|HMODULE|SMHandle|DBHandle|SOCKET|'
                    r'ULONG_PTR|LONG_PTR|UINT_PTR|INT_PTR|DWORD_PTR|WPARAM|LPARAM|LRESULT|size_t|time_t)\b|std\s*::')


def main():
    # gen_abi_asserts.py [x86.json] [x64.json] [out.h]   (defaults: Registry/abi/*.json -> Src/Shared/Common/abi_asserts.h)
    p86 = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REG, 'struct_sizes_x86.json')
    p64 = sys.argv[2] if len(sys.argv) > 2 else os.path.join(REG, 'struct_sizes_x64.json')
    out = sys.argv[3] if len(sys.argv) > 3 else OUT
    d86 = json.load(open(p86, encoding='utf-8'))
    d64 = json.load(open(p64, encoding='utf-8'))
    t86 = {t['name']: t for t in d86['types']}
    t64 = {t['name']: t for t in d64['types']}
    short = {}
    for n, t in t86.items():
        short.setdefault(n.split('::')[-1], t)

    bad_cache = {}

    def has_ptr(t, depth=0):
        if t['name'] in bad_cache:
            return bad_cache[t['name']]
        bad_cache[t['name']] = True  # recursion guard
        res = t['polymorphic']
        for f in t['fields']:
            if res:
                break
            ty = f['type']
            if PTR_RE.search(ty):
                res = True
                break
            base = re.sub(r'\[.*?\]', '', ty).replace('const', '').split()
            if base and depth < 8 and base[-1] in short and short[base[-1]]['name'] != t['name']:
                res = has_ptr(short[base[-1]], depth + 1)
        bad_cache[t['name']] = res
        return res

    headers = []
    rows = []
    for name, a in sorted(t86.items(), key=lambda kv: (kv[1]['file'].lower(), kv[1]['line'])):
        b = t64.get(name)
        if not b or '::' in name or name.startswith('<'):
            continue
        if a['polymorphic'] or a['size'] != b['size'] or has_ptr(a):
            continue
        if a['file'] not in headers:
            headers.append(a['file'])
        rows.append((a['file'], name, a['size']))

    lines = ['// Generated by Tests/abi/gen_abi_asserts.py from Registry/abi/struct_sizes_x86.json - do not edit.',
             '// CYS: sizes of the pointer-free, non-polymorphic structs of Src/Shared/Common that are identical on x86',
             '// CYS: and x64 (Docs/04 section 6). A failing assert means a wire/DB format change: update the JSON on',
             '// CYS: purpose (Tests/abi) or fix the type.',
             '#pragma once', '']
    for h in headers:
        lines.append('#include "%s"' % h)
    lines.append('')
    cur = None
    for (f, name, size) in rows:
        if f != cur:
            lines.append('// %s' % f)
            cur = f
        lines.append('static_assert(sizeof(::%s) == %d, "ABI: sizeof(%s) changed");' % (name, size, name))
    with open(out, 'w', encoding='utf-8', newline='\n') as fp:
        fp.write('﻿' + '\n'.join(lines) + '\n')  # UTF-8 BOM like the rest of Src
    print('abi_asserts.h: %d asserts from %d headers' % (len(rows), len(headers)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
