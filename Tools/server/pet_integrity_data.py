"""CY client/server Pet upgrade contract; never infer the unknown alternate cap."""
import argparse,hashlib,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'Tools/game'))
from dbc_inventory import Table
CY=Path('C:/TLBB/085/Tools/DATA NEW/DataCY31-08-26')

def upgrade_rows(cy=CY):
    server={r[0]:r for r in Table(cy/'tlbb15/Public/Config/PetSkillLevelup.txt').rows}
    client={r[0]:r for r in Table(cy/'Config/PetSkillLevelup.txt').rows}
    assert server=={k:[r[i] for i in (0,1,2,4,5)] for k,r in client.items()}, 'CY client/server upgrade contract differs'
    prices={}
    for r in client.values():prices.setdefault(r[2],set()).add(r[3])
    result={}
    for id,r in sorted(server.items()):
        c=client.get(id);highest,price=-1,0
        if c and c[6:8]==c[8:10] and c[6]>0 and c[7]>0:
            at=id;seen=set()
            while at in server and at not in seen and at!=c[6]:
                seen.add(at);at=server[at][1]
            if at==c[6] and at!=id:highest,price=c[6:8]
        item_prices=prices.get(r[2],set())
        item_price=next(iter(item_prices)) if len(item_prices)==1 else 0
        result[id]=[r[1],r[2],item_price,r[3],highest,price]
    assert len(result)==267 and result[656]==[1197,30503043,30,20000,1200,4724]
    return result

def header():
    text='// Generated by Tools/server/pet_integrity_data.py. Do not edit.\n'
    for rel in ['tlbb15/Public/Config/PetSkillLevelup.txt','Config/PetSkillLevelup.txt']:
        text+='// CY '+rel+' sha256='+hashlib.sha256((CY/rel).read_bytes()).hexdigest()+'\n'
    text+='// id, next, item, item YuanBao, coins, proven quick target (-1=unknown), quick YuanBao\n'
    text+='static const int kCyPetUpgrade[][7] = {\n'
    for id,row in upgrade_rows().items():text+='    {'+','.join(map(str,[id]+row))+'},\n'
    return (text+'};\n').encode('ascii')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    dest=ROOT/'Src/Client/WXClient/Network/CysPetUpgradeData.inl';raw=header()
    if a.check:assert dest.read_bytes()==raw
    else:dest.write_bytes(raw)
    print('verified' if a.check else 'generated',len(upgrade_rows()),'CY upgrade records')
