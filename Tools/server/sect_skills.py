def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None

def books_from_cy():
    items = Table(CY / 'CommonItem.txt')
    xinfa = {r[0]: r for r in Table(CY / 'XinFa_V1.txt').rows}
    skills = Table(CY / 'SkillTemplate_V1.txt')
    server_skills = {r[0]: r for r in Table(R / 'configs/SkillTemplate_V1.txt').rows}
    server_xinfa = {r[0]: r for r in Table(R / 'configs/XinFa_V1.txt').rows}
    server_items = {r[0]: r for r in Table(R / 'configs/CommonItem.txt').rows}
    books, evidence = {}, []
    for r in items.rows:
        if r[13] != 338000 or r[0] in BLOCKED:
            continue
        name = r[6].split('：')[-1]
        typ = 1 if r[6].startswith('秘籍：') else 2
        if typ == 1:
            pool = [x for x in xinfa.values() if x[2] == name]
            assert len(pool) == 1, (r[0], name, pool)
            target = pool[0]; tid, mp, prerequisite = target[0], target[1], -1
            assert server_xinfa[tid][1:3] == target[1:3]
        else:
            # Murong contains copies of other sects' names. Match xinfa AND faction.
            pool = [s for s in skills.rows if s[2] == name and
                    (s[0] == 37 or (s[10] in xinfa and xinfa[s[10]][2] in r[7]
                                    and xinfa[s[10]][1] == s[1]))]
            if len(pool) > 1:
                pool = [s for s in pool if s[3] == r[5]]
            assert len(pool) == 1, (r[0], name, [p[0] for p in pool])
            target = pool[0]; tid, mp, prerequisite = target[0], target[1], target[10]
            actual = server_skills[tid]
            assert (actual[2], actual[3], actual[11]) == (mp, name, prerequisite)
        assert server_items[r[0]][6] == r[6] and server_items[r[0]][13] == 338000
        # Preserve the existing extra prerequisite for this CY4 book.
        vals = (typ, tid, mp, r[8], prerequisite, 20 if r[0] == 30308283 else 1, 18)
        books[r[0]] = dict(zip(FIELDS, vals))
        evidence.append(dict(item=r[0], name=r[6], description=r[7], **books[r[0]]))
    assert len(books) == 106, len(books)
    for mp in list(range(9)) + list(range(10, 16)):
        assert sum(b['menpaiId'] == mp for b in books.values()) == 7, mp
    return books, evidence

