def apply(staging):
    manifest = json.loads((staging / 'manifest.json').read_text())
    for row in manifest:
        assert sha(staging / row['path']) == row['after'], row['path']
        assert sha(R / row['path']) in (row['before'], row['after']), 'Changed since plan: ' + row['path']
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')
    backup = R / 'backups' / ('sect-skills-' + stamp)
    backup.mkdir(parents=True)
    shutil.copy2(staging / 'manifest.json', backup / 'manifest.json')
    for row in manifest:
        rel = row['path']; target = R / rel
        assert target.resolve().is_relative_to(R.resolve())
        if sha(target) == row['after']: continue
        if target.exists():
            saved = backup / rel; saved.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(target, saved)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(staging / rel, target)
    print('backup=' + str(backup))

def audit(out):
    books, evidence = books_from_cy()
    skills = Table(R / 'configs/SkillTemplate_V1.txt')
    data = {r[0]:r for r in Table(R / 'configs/SkillData_V1.txt').rows}
    xinfa = {r[0]:r for r in Table(R / 'configs/XinFa_V1.txt').rows}
    impacts = {r[0] for r in Table(R / 'configs/StandardImpact.txt').rows}
    registry = (R / 'GameServer/lualib/skillenginer.lua').read_text(encoding='utf8')
    registered = {int(i):m for i,m in re.findall(r'\[(\d+)\]\s*=\s*"(scene\.skill\.[\w.]+)"',registry)}
    rows, per = [], {}
    for mp in list(range(9)) + list(range(10,16)):
        own = sorted(x[0] for x in xinfa.values() if x[1] == mp)
        assert len(own) == 8
        base = own[:6]
        learned = {r[0] for r in skills.rows if r[2] == mp and (r[33] == 1 or (r[24] == 0 and r[11] in base))}
        learned |= {b['id'] for b in books.values() if b['menpaiId'] == mp and b['type'] == 2}
        stats = collections.Counter()
        for t in skills.rows:
            if t[2] != mp or t[24] != 0: continue
            stats['templates'] += 1
            if t[0] in learned: stats['learnable'] += 1
            stats['active' if t[25] == 0 else 'passive'] += 1
            issues = []; logics = set()
            for level, sid in enumerate(t[58:74],1):
                if sid == -1: continue
                d = data.get(sid)
                if d is None: issues.append(dict(level=level,missing_data=sid)); continue
                logic = d[5];logics.add(logic)
                if logic < 8000 and logic not in registered:
                    issues.append(dict(level=level,logic=logic,generic_fallback=True))
                for c in range(24,54,2):
                    label, value = str(d[c]), d[c+1]
                    # Exact labels consumed by CY skill_cy_spec; never treat visual FX as impacts.
                    if re.fullmatch(r'(?:(?:附加)?效果[1-9]?|\|给目标的基础效果[12]|\|(?:生效一次|引导周期)的附加效果\d+|(?:疲劳|变身男|变身女|免控)buff)',label) and isinstance(value,(int,float)) and value>0 and value not in impacts:
                        issues.append(dict(level=level,logic=logic,label=label,missing_impact=value))
            row=dict(id=t[0],name=t[3],menpai=mp,xinfa=t[11],learnable=t[0] in learned,passive=t[25],logics=sorted(logics),issues=issues)
            rows.append(row)
            if issues: stats['needs_review'] += 1
        per[mp]=dict(stats,xinfa=own)
    report=dict(factions=per,skills=rows,books=evidence,blocked_books=sorted(BLOCKED),
                note='Static references only; does not prove damage/buff semantics or visual effects.')
    out.parent.mkdir(parents=True,exist_ok=True);out.write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf8')
    print(json.dumps(per,ensure_ascii=False,indent=2))

