def apply(out):
    manifest=json.loads((out/'manifest.json').read_text())
    for e in manifest:
        assert sha(out/e['path']) == e['after'], 'overlay changed: '+e['path']
        assert sha(R/e['path']) == e['before'], 'live drift: '+e['path']
    backup=ROOT/'Build/backups/gameplay-audit-server'/datetime.datetime.now().strftime('%Y%m%d-%H%M%S')
    for e in manifest:
        live=R/e['path'];saved=backup/e['path']
        saved.parent.mkdir(parents=True,exist_ok=True)
        if live.exists(): shutil.copy2(live,saved)
        live.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(out/e['path'],live)
        assert sha(live)==e['after']
    shutil.copy2(out/'manifest.json',backup/'manifest.json')
    print('Applied',len(manifest),'files; backup:',backup)

