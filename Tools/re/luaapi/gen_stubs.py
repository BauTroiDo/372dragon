# -*- coding: utf-8 -*-
"""Generate C++ stub registrations for the Lua host functions that B (client/client_GL Bin64) registers
but the 0.85 source does not register on the same receiver.

Every stub logs "missing host function <Receiver>:<Name>" once per session, counts every call, and
returns neutral values that match the return pattern recovered from B (catalog.json):
    number -> 0, string -> "", boolean -> false, nil -> nil, table -> {},
    object/userdata/unknown-type -> a shared "null object" (any method call on it returns nothing)
    unknown return count -> no values.
Registration uses the 0.85 LuaPlus style:  metaTable.Register("Name", Fn)  /  objGlobal.Register(...)
and never overrides an existing entry (real implementations always win).

Usage:
  python gen_stubs.py [--catalog <catalog.json>] [--out <dir>] [--include-085] [--manifest <tsv>]
Defaults: --catalog CY-Source/Registry/luaapi/catalog.json  --out CY-Source/Src/Client/LuaApiGen
          --manifest CY-Source/Build/re/luaapi/stubs_manifest.tsv
Adoption (game layer, later): add Src/Client/LuaApiGen/*.cpp to the WXClient target and call
  LuaApiGen::RegisterAll(pLuaState);   after CScriptSystem has registered the real API.
"""
import argparse, collections, json, os, re

CY = r'C:\TLBB\085\CY-Source'
TYPE_CODE = {'number': 'n', 'int': 'n', 'string': 's', 'boolean': 'b', 'nil': 'z', 'table': 't',
             'value': 'o', 'object': 'o', 'userdata': 'o', 'function': 'o', '?': 'o'}
KIND_GLOBALS, KIND_BOXED, KIND_UI_META, KIND_META_ONLY, KIND_TABLE = 0, 1, 2, 3, 4
KIND_NAME = {0: 'LAG_KIND_GLOBALS', 1: 'LAG_KIND_BOXED', 2: 'LAG_KIND_UI_META', 3: 'LAG_KIND_META_ONLY', 4: 'LAG_KIND_TABLE'}


def ident(s):
    s = re.sub(r'\W', '_', s)
    return ('_' + s) if s[:1].isdigit() else s


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def group_name(mod, receiver):
    if receiver == '_G':
        return 'Globals' if mod == 'Game.exe' else 'UI_Globals'
    if mod == 'UI_CEGUI.dll':
        return 'UI_' + ident(receiver.replace('MetaTable_Control_', '').replace('MetaTable_', ''))
    return ident(receiver)


def ret_codes(e):
    n = e.get('returns_n')
    if n is None:
        return None
    types = list(e.get('returns_types') or [])
    types += ['?'] * (n - len(types))
    return ''.join(TYPE_CODE.get(t, 'o') for t in types[:n])


HEADER = r'''// LuaApiGen.h - GENERATED by CY-Source/Tools/re/luaapi/gen_stubs.py from Registry/luaapi/catalog.json.
// Do not edit by hand: re-run the generator.
//
// Stub registrations for the Lua host API that the modern client (B: client\Bin64 Game.exe + UI_CEGUI.dll,
// byte-identical code in client_GL\Bin64) registers but the 0.85 source does not.  Each stub logs
// "missing host function <Receiver>:<Name>" once per session, counts every call (G2 gate counter) and
// returns neutral values matching the return pattern recovered from B.  Registration never overrides
// an existing function, so real implementations (0.85 or new) always win.
//
// Adoption (game layer): compile Src/Client/LuaApiGen/*.cpp into Game.exe and call
//     LuaApiGen::RegisterAll(pLuaState);
// at the end of the script-system registration (after GMScriptSystm.cpp / UILuaControl.cpp).
#pragma once

#include "LuaPlus.h"

namespace LuaApiGen
{
    typedef void (*LogSink)(const char* line);

    enum ReceiverKind
    {
        LAG_KIND_GLOBALS = 0,   // global functions (registered into _G)
        LAG_KIND_BOXED = 1,     // boxed global object(s) + metatable (created if the game layer lacks them)
        LAG_KIND_UI_META = 2,   // UI control metatable (MetaTable_Control_*): extended only if it exists
        LAG_KIND_META_ONLY = 3, // metatable used by runtime objects (e.g. action items): extended only if it exists
        LAG_KIND_TABLE = 4      // a plain global table (functions called with '.' or ':')
    };

    struct ReceiverInfo
    {
        const char* module;       // B module that registers it (Game.exe / UI_CEGUI.dll)
        const char* receiver;     // Lua receiver as used by the UI scripts
        const char* metaTable;    // B's CreateTable name
        const char* globals[8];   // global names published with this metatable (0-terminated)
        int kind;                 // ReceiverKind
        int stubCount;
        void (*registerFn)(LuaPlus::LuaObject& table);
    };

    // API
    void RegisterAll(LuaPlus::LuaState* pState);
    void SetLogSink(LogSink sink);
    unsigned int GetMissingCallCount();       // every call to a stub
    unsigned int GetMissingDistinctCount();   // distinct stubs called this session
    // CYS: cumulative per-stub telemetry; call on the same thread as the Lua state.
    unsigned long long GetMissingCallCountFor(const char* receiver, const char* name);
    void DumpMissingCallCounts(unsigned int limit = 20);
    void ResetMissingCallCounts();             // explicit new session; RegisterAll does not reset
    const ReceiverInfo* GetReceivers(int* count);

    // used by the generated per-receiver files
    int Stub(LuaPlus::LuaState* state, const char* receiver, const char* name, const char* rets);
    bool IsMissing(LuaPlus::LuaObject& table, const char* name);
'''

COMMON = r'''// LuaApiGen_Common.cpp - GENERATED by CY-Source/Tools/re/luaapi/gen_stubs.py. Do not edit by hand.
// Shared runtime of the generated host-API stubs: once-per-session logging, call counters,
// neutral return values and the "null object".
#include "LuaApiGen.h"

#include <algorithm>
#include <locale>
#include <map>
#include <sstream>
#include <string>
#include <vector>
#include <windows.h>

namespace LuaApiGen
{
    namespace
    {
        const char* const kNullObject = "LuaApiGen_NullObject";
        const char* const kNullObjectMeta = "LuaApiGen_NullObjectMeta";
        // CYS: retain exact per-stub counts independently of the legacy 32-bit API.
        unsigned long long s_calls = 0;
        typedef std::map<std::string, unsigned long long> CallCounts;
        typedef std::pair<std::string, unsigned long long> CountEntry;

        CallCounts& Counts()
        {
            static CallCounts s_counts;
            return s_counts;
        }

        bool CountOrder(const CountEntry& a, const CountEntry& b)
        {
            return a.second != b.second ? a.second > b.second : a.first < b.first;
        }

        void DefaultSink(const char* line)
        {
            ::OutputDebugStringA(line);
            ::OutputDebugStringA("\n");
        }

        LogSink s_sink = DefaultSink;

        int NullCall(lua_State*) { return 0; }

        // __index of the null object: every key resolves to a function returning nothing
        int NullIndex(lua_State* L)
        {
            lua_pushcclosure(L, NullCall, 0);
            return 1;
        }

        void PushNullObject(LuaPlus::LuaState* state)
        {
            LuaPlus::LuaObject o = state->GetGlobals().GetByName(kNullObject);
            if (o.IsTable())
                o.PushStack();
            else
                state->PushNil();
        }
    }

    void SetLogSink(LogSink sink) { s_sink = sink ? sink : DefaultSink; }
    unsigned int GetMissingCallCount() { return (unsigned int)s_calls; }
    unsigned int GetMissingDistinctCount() { return (unsigned int)Counts().size(); }

    unsigned long long GetMissingCallCountFor(const char* receiver, const char* name)
    {
        if (!receiver || !name)
            return 0;
        const CallCounts& counts = Counts();
        CallCounts::const_iterator found = counts.find(std::string(receiver) + ":" + name);
        return found == counts.end() ? 0 : found->second;
    }

    void ResetMissingCallCounts()
    {
        Counts().clear();
        s_calls = 0;
    }

    void DumpMissingCallCounts(unsigned int limit)
    {
        const CallCounts& counts = Counts();
        std::vector<CountEntry> entries(counts.begin(), counts.end());
        const unsigned long long total = s_calls;
        std::sort(entries.begin(), entries.end(), CountOrder);
        const size_t shown = entries.size() < limit ? entries.size() : limit;
        std::ostringstream line;
        line.imbue(std::locale::classic());
        line << "LuaApiGen missing calls begin total=" << total
             << " distinct=" << entries.size() << " shown=" << shown;
        s_sink(line.str().c_str());
        for (size_t i = 0; i < shown; ++i)
        {
            line.str("");
            line.clear();
            line << "LuaApiGen missing calls item count=" << entries[i].second
                 << " function=" << entries[i].first;
            s_sink(line.str().c_str());
        }
        s_sink("LuaApiGen missing calls end");
    }

    bool IsMissing(LuaPlus::LuaObject& table, const char* name)
    {
        LuaPlus::LuaObject o = table.GetByName(name);
        return o.IsNil();
    }

    int Stub(LuaPlus::LuaState* state, const char* receiver, const char* name, const char* rets)
    {
        ++s_calls;
        std::string key = std::string(receiver) + ":" + name;
        if (++Counts()[key] == 1)
        {
            std::string line = "missing host function " + key;
            s_sink(line.c_str());
        }
        int n = 0;
        for (const char* p = rets; *p; ++p, ++n)
        {
            switch (*p)
            {
            case 'n': state->PushNumber(0); break;
            case 's': state->PushString(""); break;
            case 'b': state->PushBoolean(false); break;
            case 'z': state->PushNil(); break;
            case 't': state->NewTable(); break;
            default: PushNullObject(state); break;
            }
        }
        return n;
    }

    void CreateNullObject(LuaPlus::LuaObject& objGlobal)
    {
        if (!objGlobal.GetByName(kNullObject).IsNil())
            return;
        LuaPlus::LuaObject meta = objGlobal.CreateTable(kNullObjectMeta);
        meta.Register("__index", NullIndex);
        LuaPlus::LuaObject obj = objGlobal.CreateTable(kNullObject);
        obj.SetMetaTable(meta);
    }
}
'''

REGISTRY_HEAD = r'''// LuaApiGen_Registry.cpp - GENERATED by CY-Source/Tools/re/luaapi/gen_stubs.py. Do not edit by hand.
// Receiver table + RegisterAll().
#include "LuaApiGen.h"
#include <cstring>

namespace LuaApiGen
{
    void CreateNullObject(LuaPlus::LuaObject& objGlobal);
%(decls)s

    namespace
    {
        const ReceiverInfo kReceivers[] =
        {
%(rows)s
        };

        char s_placeholder[64];   // boxed by receivers the game layer does not publish yet

        void MissingReceiverNote(const char* what, const char* name)
        {
            // logged through the stub reporter so it shows up once in the same log
            (void)what; (void)name;
        }

        void AttachBoxed(LuaPlus::LuaState* pState, LuaPlus::LuaObject& objGlobal, const ReceiverInfo& ri)
        {
            lua_State* L = pState->GetCState();
            int top = lua_gettop(L);
            LuaPlus::LuaObject meta;
            bool have = false;
            // 1) the game layer already publishes the object: extend its own metatable
            for (int i = 0; i < 8 && ri.globals[i] && !have; ++i)
            {
                LuaPlus::LuaObject obj = objGlobal.GetByName(ri.globals[i]);
                if (obj.IsNil())
                    continue;
                LuaPlus::LuaObject mt = obj.GetMetaTable();
                if (mt.IsTable()) { meta = mt; have = true; }
            }
            // 2) B's metatable name
            if (!have)
            {
                LuaPlus::LuaObject mt = objGlobal.GetByName(ri.metaTable);
                if (mt.IsTable()) { meta = mt; have = true; }
            }
            // 3) create it (receiver unknown to the game layer)
            if (!have)
            {
                meta = objGlobal.CreateTable(ri.metaTable);
                meta.SetObject("__index", meta);
            }
            ri.registerFn(meta);
            for (int i = 0; i < 8 && ri.globals[i]; ++i)
            {
                if (!objGlobal.GetByName(ri.globals[i]).IsNil())
                    continue;
                LuaPlus::LuaObject obj = pState->BoxPointer(s_placeholder);
                obj.SetMetaTable(meta);
                objGlobal.SetObject(ri.globals[i], obj);
            }
            lua_settop(L, top);
        }
    }

    const ReceiverInfo* GetReceivers(int* count)
    {
        if (count)
            *count = (int)(sizeof(kReceivers) / sizeof(kReceivers[0]));
        return kReceivers;
    }

    void RegisterAll(LuaPlus::LuaState* pState)
    {
        LuaPlus::LuaObject objGlobal = pState->GetGlobals();
        CreateNullObject(objGlobal);
        for (int i = 0; i < (int)(sizeof(kReceivers) / sizeof(kReceivers[0])); ++i)
        {
            const ReceiverInfo& ri = kReceivers[i];
            switch (ri.kind)
            {
            case LAG_KIND_GLOBALS:
                ri.registerFn(objGlobal);
                break;
            case LAG_KIND_BOXED:
                AttachBoxed(pState, objGlobal, ri);
                break;
            case LAG_KIND_TABLE:
            {
                LuaPlus::LuaObject t = objGlobal.GetByName(ri.globals[0] ? ri.globals[0] : ri.metaTable);
                if (!t.IsTable())
                    t = objGlobal.CreateTable(ri.globals[0] ? ri.globals[0] : ri.metaTable);
                ri.registerFn(t);
                break;
            }
            default:   // LAG_KIND_UI_META / LAG_KIND_META_ONLY: only extend what the engine created
            {
                LuaPlus::LuaObject mt = objGlobal.GetByName(ri.metaTable);
                // CYS-CYGUI2: every CEGUI control of UILuaControl.cpp shares MetaTable_Control_Window, and control
                // classes the 0.85 UI never had (AnimateButton, SuperBarButton, AchievementBarWindowButton, ...)
                // have no metatable at all: extend the shared table so their B methods reach the CY controls
                // (MainMenuBar.lua Button_Team:PlayWarning, replay-6). Only for UI_CEGUI control metatables.
                if (!mt.IsTable() && ri.kind == LAG_KIND_UI_META && std::strncmp(ri.metaTable, "MetaTable_Control_", 18) == 0)
                    mt = objGlobal.GetByName("MetaTable_Control_Window");
                if (mt.IsTable())
                    ri.registerFn(mt);
                else
                    MissingReceiverNote("metatable", ri.metaTable);
                break;
            }
            }
        }
    }
}
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--catalog', default=os.path.join(CY, r'Registry\luaapi\catalog.json'))
    ap.add_argument('--out', default=os.path.join(CY, r'Src\Client\LuaApiGen'))
    ap.add_argument('--manifest', default=os.path.join(CY, r'Build\re\luaapi\stubs_manifest.tsv'))
    ap.add_argument('--include-085', action='store_true', help='also stub names the 0.85 source already registers on that receiver')
    a = ap.parse_args()
    cat = json.load(open(a.catalog, encoding='utf-8'))
    entries = cat['entries']
    sel = [e for e in entries if a.include_085 or not e['in_085_same_receiver']]
    groups = collections.OrderedDict()
    for e in sorted(sel, key=lambda e: (e['module'] != 'Game.exe', e['receiver'], e['name'])):
        groups.setdefault((e['module'], e['receiver']), []).append(e)
    # all globals / metatable per receiver (from every entry, not only the missing ones)
    rinfo = {}
    for e in entries:
        k = (e['module'], e['receiver'])
        ri = rinfo.setdefault(k, {'meta': e.get('metatable') or e['receiver'], 'globals': []})
        for g in e.get('globals') or []:
            if g not in ri['globals']:
                ri['globals'].append(g)
    os.makedirs(a.out, exist_ok=True)
    for f in os.listdir(a.out):
        if f.startswith('LuaApiGen') and f.endswith(('.cpp', '.h')):
            os.remove(os.path.join(a.out, f))
    decls, rows, manifest = [], [], []
    used_files = set()
    for (mod, recv), es in groups.items():
        g = group_name(mod, recv)
        base = g
        i = 2
        while g in used_files:
            g = '%s_%d' % (base, i)
            i += 1
        used_files.add(g)
        ri = rinfo[(mod, recv)]
        # env-scoped names (e.g. a window script's "this") are never published as globals
        gl = [x for x in ri['globals'] if '(env)' not in x]
        if recv == '_G':
            kind = KIND_GLOBALS
        elif any(x.endswith('(table)') for x in gl):
            kind = KIND_TABLE
        elif (ri['meta'] or '').startswith('MetaTable_') and mod == 'UI_CEGUI.dll':
            kind = KIND_UI_META
        elif gl:
            kind = KIND_BOXED
        else:
            kind = KIND_META_ONLY
        gl_clean = [x.replace('(table)', '') for x in gl if '.' not in x][:7]
        fn_reg = 'Register_' + g
        lines = []
        lines.append('// LuaApiGen_%s.cpp - GENERATED by CY-Source/Tools/re/luaapi/gen_stubs.py from Registry/luaapi/catalog.json.' % g)
        lines.append('// Do not edit by hand. Receiver "%s" (module %s, B metatable "%s", globals: %s).' % (recv, mod, ri['meta'], ', '.join(gl) or '-'))
        lines.append('// %d host functions registered by B but not by the 0.85 source on this receiver.' % len(es))
        lines.append('// Evidence per stub: B RVA of the implementing function, Lua stack reads (args) and results (returns)')
        lines.append('// recovered from its LuaPlus calls; subsystem is INFERENCE. See Registry/luaapi/catalog.tsv.')
        lines.append('#include "LuaApiGen.h"')
        lines.append('')
        lines.append('namespace LuaApiGen')
        lines.append('{')
        lines.append('    namespace')
        lines.append('    {')
        reg_lines = []
        seen = set()
        for e in es:
            if e['name'] in seen:
                continue
            seen.add(e['name'])
            codes = ret_codes(e)
            fid = 'LAG_%s_%s' % (g, ident(e['name']))
            pk = ','.join(p['class'] + ('#%d' % p['id'] if p.get('id') is not None else '') for p in e.get('packets') or [])
            lines.append('        // %s  B %s+%s (%s)  args: %s  returns: %s [%s]  calls: %s/%s  conf: %s' % (
                e['name'], e['module'], e['rva'], e['impl_kind'] + ('/' + e['vcall_class'] if e.get('vcall_class') else ''),
                e['args'] or '-', e['returns'], e['returns_how'], e['calls_exact'], e['calls_any'], e['confidence']))
            extra = []
            if e.get('subsystem') and e['subsystem'] != recv:
                extra.append('subsystem(INFERENCE): %s' % e['subsystem'])
            if pk:
                extra.append('packets: %s' % pk)
            if e.get('impl_085'):
                extra.append('0.85 has it elsewhere: %s' % e['impl_085'])
            if extra:
                lines.append('        //   ' + '; '.join(extra))
            if codes is None:
                lines.append('        //   return count not recovered -> returns no values')
            lines.append('        int %s(LuaPlus::LuaState* state) { return Stub(state, %s, %s, %s); }' % (
                fid, cstr(recv), cstr(e['name']), cstr(codes or '')))
            reg_lines.append('        if (IsMissing(table, %s)) table.Register(%s, %s);' % (cstr(e['name']), cstr(e['name']), fid))
            manifest.append('\t'.join([g, mod, recv, e['name'], e['rva'] or '', codes if codes is not None else '?', str(e['calls_exact']), e['confidence']]))
        lines.append('    }')
        lines.append('')
        lines.append('    void %s(LuaPlus::LuaObject& table)' % fn_reg)
        lines.append('    {')
        lines.extend(reg_lines)
        lines.append('    }')
        lines.append('}')
        with open(os.path.join(a.out, 'LuaApiGen_%s.cpp' % g), 'w', encoding='utf-8-sig', newline='\r\n') as f:
            f.write('\n'.join(lines) + '\n')
        decls.append('    void %s(LuaPlus::LuaObject& table);' % fn_reg)
        gl_init = ', '.join(cstr(x) for x in gl_clean) + (', ' if gl_clean else '') + '0'
        rows.append('            { %s, %s, %s, { %s }, %s, %d, %s },' % (cstr(mod), cstr(recv), cstr(ri['meta']), gl_init, KIND_NAME[kind], len(seen), fn_reg))
    with open(os.path.join(a.out, 'LuaApiGen.h'), 'w', encoding='utf-8-sig', newline='\r\n') as f:
        f.write(HEADER)
        f.write('\n    // per-receiver registration functions (generated)\n')
        f.write('\n'.join(decls) + '\n}\n')
    with open(os.path.join(a.out, 'LuaApiGen_Common.cpp'), 'w', encoding='utf-8-sig', newline='\r\n') as f:
        f.write(COMMON)
    with open(os.path.join(a.out, 'LuaApiGen_Registry.cpp'), 'w', encoding='utf-8-sig', newline='\r\n') as f:
        f.write(REGISTRY_HEAD % {'decls': '\n'.join(decls), 'rows': '\n'.join(rows)})
    os.makedirs(os.path.dirname(a.manifest), exist_ok=True)
    with open(a.manifest, 'w', encoding='utf-8', newline='\n') as f:
        f.write('file\tmodule\treceiver\tname\trva\tret_codes\tcalls\tconfidence\n')
        f.write('\n'.join(manifest) + '\n')
    print('stubs: %d in %d receiver files -> %s' % (len(manifest), len(groups), a.out))
    cnt = collections.Counter(m.split('\t')[0] for m in manifest)
    print('largest:', ', '.join('%s=%d' % x for x in cnt.most_common(12)))


if __name__ == '__main__':
    main()
