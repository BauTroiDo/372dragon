"""Generate display tables from the running private server; GL supplies names/icons only."""
from pathlib import Path
import json
from dbc_inventory import Table
ROOT=Path(__file__).resolve().parents[2]
SERVER=Path('//wsl.localhost/TLBB/home/ubuntu/cys-test-20260913/configs')
GL=ROOT.parent/'client_GL/Data/ConfigFolder'

def generate():
    apt=Table(SERVER/'ItemAptRate.txt')
    dw=Table(SERVER/'DiaowenInfo.txt'); translated={r[0]:r for r in Table(GL/'DiaowenInfo.txt').rows}
    gems=Table(SERVER/'GemInfo.txt'); gemnames={r[0]:r for r in Table(GL/'GemInfo.txt').rows}
    rank=Table(SERVER/'DWJinJieInfo.txt')
    q=lambda v:'u8'+json.dumps(v,ensure_ascii=False)
    out=['#pragma once','// Generated by Tools/game/equipment_tooltip_data.py. Numeric source: private server configs.',
         'namespace CysTooltipTables {','struct Apt {int point; int percent[6];};','static const Apt apt[] = {']
    # Base display order attack P/M, defence P/M, hit, miss. Named columns avoid swapped hit/miss.
    for r in apt.rows:
        by=dict(zip(apt.names,r)); vals=[by[n] for n in ['外攻','内攻','外防','内防','命中','闪避']]
        out.append('{%d,{%s}},'%(r[0],','.join(map(str,vals))))
    out+=['};','inline int AptPercent(int point,int base) {for(const auto& r:apt)if(r.point==point)return r.percent[base];return 0;}',
          'struct Effect {int bit,value;};','struct Detail {int id,level;const char* name;const char* icon;Effect attrs[6];int skill;};']
    # Attribute names/order come from GemInfo's CY 0..57 block. Diaowen inserts one unused column after HP.
    attrnames=gems.names[11:69]
    for name,table,names,ni,li,ii in [('diaowen',dw,translated,2,3,4),('gems',gems,gemnames,7,4,5)]:
        out+=['static const Detail '+name+'[] = {']
        for r in table.rows:
            tr=names.get(r[0],r); by=dict(zip(table.names,r)); effects=[]
            for bit,key in enumerate(attrnames):
                value=by.get(key,0)
                if isinstance(value,int) and value>0:effects.append((bit,value))
            assert len(effects)<=6,(name,r[0],effects)
            # GL's numerical data may differ; never use it as the stat authority.
            out.append('{%d,%d,%s,%s,{%s},%d},'%(r[0],r[li],q(tr[ni]),q(tr[ii]),
                ','.join('{%d,%d}'%v for v in effects),by.get('技能ID',-1)))
        out+=['};']
    out+=['struct Rank {int level,one,element;};','static const Rank ranks[] = {']
    out+=['{%d,%d,%d},'%(r[0],r[2],r[3]) for r in rank.rows]
    out+=['};','inline const Detail* Diaowen(int id){for(const auto& r:diaowen)if(r.id==id)return &r;return nullptr;}',
          'inline const Detail* Gem(int id){for(const auto& r:gems)if(r.id==id)return &r;return nullptr;}',
          'inline const Rank* Advance(int n){for(const auto& r:ranks)if(r.level==n)return &r;return nullptr;}','}']
    return ('\n'.join(out)+'\n').encode('utf8')

if __name__=='__main__':
    p=ROOT/'Src/Client/WXClient/Network/CysEquipmentTooltipTables.h'; p.write_bytes(generate());print('Generated',p)
