"""Reproduce client labels/proficiency limits from existing CY/server tables."""
from pathlib import Path
import json
from dbc_inventory import Table
ROOT=Path(__file__).resolve().parents[2]
SERVER=Path('//wsl.localhost/TLBB/home/ubuntu/cys-test-20260913/configs')
lines=['// Generated by Tools/game/generate_crafting_metadata.py; authored CY data.','#pragma once','inline const char* CysRecipeKind(int id) { switch(id) {']
labels={1:'Đao, phủ',2:'Thương, côn',3:'Đoản binh',4:'Song đoản',5:'Quạt',6:'Vòng',7:'Mũ',8:'Áo',9:'Găng tay',10:'Giày',11:'Dây chuyền',12:'Nhẫn',13:'Hộ phù',14:'Thuốc hồi phục',15:'Thuốc tăng cường',16:'Món chính',17:'Món ăn',18:'Công thức chung',19:'Môn phái',20:'Ngũ cốc',21:'Tạp vật',22:'Sơ chế thực phẩm',23:'Hộ uyển',24:'Hộ kiên',25:'Đai lưng',26:'Mảnh đúc',27:'Mảnh vải',28:'Chuyển đổi nguyên liệu',29:'Nguyên liệu thời trang'}
for row in Table(ROOT/'Assets/CanonicalCY/Data/ConfigFolder/RecipeKind.txt').rows:
 lines.append('case %d: return u8%s;'%(row[0],json.dumps(labels.get(row[0],row[1]),ensure_ascii=False)))
lines+=['default:return "";}}','inline int CysAbilityExpLimit(int ability,int level) { switch(ability) {']
for row in Table(SERVER/'Ability.txt').rows:
 path=SERVER/'AbilityLevelUp'/row[4]
 if not path.is_file():continue
 t=Table(path)
 index=t.names.index('本级熟练度的上限')
 lines.append('case %d: switch(level) {'%row[0])
 for r in t.rows:lines.append('case %d:return %d;'%(r[0],max(0,r[index])//100))
 lines.append('default:return 0;}')
lines+=['default:return 0;}}']
(ROOT/'Src/Client/WXClient/Network/CysCraftingMetadata.h').write_text('\n'.join(lines)+'\n',encoding='utf8')
print('Generated authored recipe labels and profession proficiency caps')
