"""Generate authoritative title metadata; old/new title tables reuse IDs.

Names and IA/IV come from the running CY server's GBK table, not row offsets
in GL's unrelated CharTitle.txt. This generator does not change server data.
"""
from pathlib import Path
import json,hashlib
ROOT=Path(__file__).resolve().parents[2]
SOURCE=Path('//wsl.localhost/TLBB/home/ubuntu/cys-test-20260913/configs/CharTitleNew.txt')
def generate():
 raw=SOURCE.read_bytes();rows=[]
 labels={0:'Sinh lực tối đa',1:'Hệ số sinh lực',6:'Băng công',8:'Giảm thời gian băng',9:'Hỏa công',11:'Giảm thời gian hỏa',12:'Huyền công',14:'Giảm thời gian huyền',15:'Độc công',17:'Giảm thời gian độc',20:'Hệ số ngoại công',27:'Hệ số nội công',35:'Chính xác',36:'Né tránh',37:'Hội công',44:'Thể lực',46:'Thân pháp',48:'Tất cả thuộc tính cơ bản'}
 for line in raw.decode('gbk').splitlines()[2:]:
  c=line.split('\t')
  if len(c)!=53 or not c[0].isdigit():continue
  attrs='; '.join(labels[int(c[i])]+' +'+c[i+1] for i in range(13,25,2) if int(c[i])>=0 and int(c[i+1])>0)
  rows.append((int(c[0]),c[2],c[3],c[7],attrs))
 assert len(rows)>1000 and len({r[0]for r in rows})==len(rows)
 quote=lambda x:'u8'+json.dumps(x,ensure_ascii=False)
 code=['#pragma once','// Generated by Tools/game/community_titles.py; server table SHA256 '+hashlib.sha256(raw).hexdigest(),
 'namespace CysTitleMetadata {','struct Entry {int id;const char* name;const char* description;const char* source;const char* attributes;};',
 'inline const Entry* Find(int id) {','static const Entry rows[]={']
 code += ['{%d,%s,%s,%s,%s},'%(i,quote(n),quote(d),quote(s),quote(a))for i,n,d,s,a in sorted(rows)]
 code += ['};','int lo=0,hi=int(sizeof(rows)/sizeof(rows[0]));while(lo<hi){int m=(lo+hi)/2;if(rows[m].id<id)lo=m+1;else hi=m;}return lo<int(sizeof(rows)/sizeof(rows[0]))&&rows[lo].id==id?&rows[lo]:nullptr;','}','}']
 (ROOT/'Src/Client/WXClient/DBC/CysTitleMetadata.h').write_text('\n'.join(code)+'\n',encoding='utf8')
 print('Generated',len(rows),'authoritative title IDs')
if __name__=='__main__':generate()
