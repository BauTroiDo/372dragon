"""Generate the small native ornament lookup from the same CY catalog as the UI.

Object filenames use the resource manager's GBK byte spelling, not display UTF-8.
"""
from pathlib import Path
from wardrobe_catalog import build

def generate():
    c=build()
    def literal(s): return '"'+''.join('\\%03o'%b for b in s.encode('gbk'))+'"'
    out=['// Generated by Tools/game/wardrobe_render_data.py; do not edit.', '#pragma once',
         'namespace CysOrnamentData {',
         'struct Row { int category,id; const char* model[2]; int position[2]; float step[2][3]; int bounds[6]; const char* idle[3]; };',
         'static const Row rows[] = {']
    for cat in (5,6):
        for r in c['categories'][cat]:
            pos=[p[0]|p[1]<<8|p[2]<<16 for p in r['pos']]
            step=['{'+','.join(format(x,'.9f')+'f' for x in s)+'}' for s in r['scale']]
            idle=(r.get('idle') or ['','',''])
            out.append('{%d,%d,{%s,%s},{%d,%d},{%s,%s},{%s},{%s}},'%(cat,r['native'],literal(r['obj'][0]),literal(r['obj'][1]),*pos,*step,','.join(map(str,r['bounds'])),','.join(literal(x) for x in idle)))
    out += ['};','inline const Row* Find(int category,int id) { for(const auto& r:rows) if(r.category==category&&r.id==id) return &r; return nullptr; }','}']
    dest=Path(__file__).resolve().parents[2]/'Src/Client/WXClient/DataPool/CysOrnamentData.h'
    dest.write_text('\n'.join(out)+'\n',encoding='ascii',newline='\n')
    actions=['// Generated by Tools/game/wardrobe_render_data.py; do not edit.','#pragma once',
             'namespace CysExteriorActionData {','struct Row { int category,id,index,item; const char* order; };','static const Row rows[] = {']
    for cat in (6,7):
        for row in c['categories'][cat]:
            for i,a in enumerate(row.get('actions',[]),1):
                actions.append('{%d,%d,%d,%d,%s},'%(cat,row['id'],i,row['visual'][0],literal(a['order'])))
    actions+=['};','inline const Row* Find(int cat,int id,int index) { for(const auto& r:rows) if(r.category==cat&&r.id==id&&r.index==index) return &r; return nullptr; }','}']
    dest.with_name('CysExteriorActionData.h').write_text('\n'.join(actions)+'\n',encoding='ascii',newline='\n')
    weapons=['// Generated by Tools/game/wardrobe_render_data.py; do not edit.','#pragma once',
             'namespace CysExteriorWeaponData {','struct Row { int native,item; };','static const Row rows[] = {']
    weapons+=['{%d,%d},'%(r['native'],r['visual'][0]) for r in c['categories'][7]]
    weapons+=['};','inline int Item(int native) { for(const auto& r:rows) if(r.native==native) return r.item; return -1; }','}']
    dest.with_name('CysExteriorWeaponData.h').write_text('\n'.join(weapons)+'\n',encoding='ascii',newline='\n')
    print('Generated',len(c['categories'][5])+len(c['categories'][6]),'ornament rows')
if __name__=='__main__':generate()
