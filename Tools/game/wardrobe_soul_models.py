"""Validate explicit CY soul-model links and generate the native-byte fallback.

No assets or reference DBCs are modified. Run --write-header after an audited
mapping change; normal catalog builds check the authored object names exist.
"""
from pathlib import Path
import argparse
import json
import re

def repairs(root):
    data=json.loads(Path(__file__).with_suffix('.json').read_text(encoding='utf-8'))
    objects=(root/'Assets/CanonicalCY/Data/ModelFolder/all.obj').read_bytes()
    names=set(re.findall(rb'<Object name="([^"]+)"',objects))
    result={}
    for row in data['repairs']:
        assert row['model'].encode('gbk') in names, row
        assert row['previousModel'].encode('gbk') in names, row
        assert row['modelId'] not in result, row
        result[row['modelId']]=row['model']
    return result

def header(mapping):
    def native(s): return '"'+''.join('\\%03o'%c for c in s.encode('gbk'))+'"'
    lines=['// Generated by Tools/game/wardrobe_soul_models.py --write-header.',
           '// Authored CY level-five links; never substitute GL model IDs.',
           '#pragma once','namespace CysSoulVisualData {',
           'struct Row {int id;const char* name;};','static const Row rows[]={']
    lines += ['{%d,%s},'%(id,native(name)) for id,name in sorted(mapping.items())]
    return '\n'.join(lines+['};','}',''])

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--write-header',action='store_true');a=p.parse_args()
    repo=Path(__file__).resolve().parents[2]
    root=next(x for x in (repo,*repo.parents) if (x/'Assets/CanonicalCY').is_dir())
    content=header(repairs(root))
    target=repo/'Src/Client/WXClient/DataPool/CysSoulVisualData.h'
    if a.write_header: target.write_text(content,encoding='ascii')
    assert target.read_text(encoding='ascii')==content,'regenerate soul header'
    print('18 authored soul model links: PASS')
