"""Read-only reference extraction; generate tooltip bonuses from actual ItemEnhance."""
from pathlib import Path
from dbc_inventory import Table

ROOT=Path(__file__).resolve().parents[2]
def generate():
    client=Table(ROOT/'Assets/CanonicalCY/Data/ConfigFolder/ItemEnhance.txt')
    server=Table(Path('//wsl.localhost/TLBB/home/ubuntu/cys-test-20260913/configs/ItemEnhance.txt'))
    rows={(int(r[1]),int(r[2])):tuple(int(v) for v in r[6:12]) for r in client.rows}
    live={(int(r[1]),int(r[2])):tuple(int(v) for v in r[6:12]) for r in server.rows}
    assert all(rows[k]==v for k,v in live.items() if k in rows),'Shared tooltip bonuses must match server'
    lines=['#pragma once','// Generated by Tools/game/round2_data.py from ItemEnhance.txt, verified against private server.',
           'namespace CysEnhanceBonuses {','struct Row { int slot,level; int percent[6]; };','static const Row rows[] = {']
    for (slot,level),values in sorted(live.items()):
        lines.append('{%d,%d,{%s}},'%(slot,level,','.join(map(str,values))))
    lines+=['};','inline const Row* Find(int slot,int level) { for(const auto& r:rows) if(r.slot==slot && r.level==level) return &r; return nullptr; }','}']
    (ROOT/'Src/Client/WXClient/Network/CysEnhanceBonuses.h').write_text('\n'.join(lines)+'\n',encoding='utf8')
    print('PASS',len(live),'server enhancement rows; shared client rows match')
if __name__=='__main__':generate()
